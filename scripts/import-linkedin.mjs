// Turns LinkedIn's official data export into src/data/credentials.generated.ts.
// LinkedIn: Settings -> Data privacy -> Get a copy of your data -> pick "Certifications" -> download.
// Usage: npm run import:linkedin -- path/to/Certifications.csv
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const file = process.argv[2];
if (!file) {
  console.error("Usage: npm run import:linkedin -- path/to/Certifications.csv");
  process.exit(1);
}

const parseCsv = (text) => {
  const rows = [];
  let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); cell = "";
      if (row.some((x) => x.trim())) rows.push(row);
      row = [];
    } else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
};

const rows = parseCsv(readFileSync(resolve(file), "utf8").replace(/^﻿/, ""));
const head = (rows.shift() || []).map((h) => h.trim().toLowerCase());
const col = (r, name) => (r[head.indexOf(name)] || "").trim();

const months = { jan: 1, feb: 2, mar: 3, apr: 4, may: 5, jun: 6, jul: 7, aug: 8, sep: 9, oct: 10, nov: 11, dec: 12 };
const toIso = (s) => {
  const m = /^([A-Za-z]{3})[a-z]*\s+(\d{4})$/.exec(s);
  if (m && months[m[1].toLowerCase()]) return `${m[2]}-${String(months[m[1].toLowerCase()]).padStart(2, "0")}`;
  return /^\d{4}(-\d{2})?$/.test(s) ? s : "";
};
const guess = (t) => {
  const s = t.toLowerCase();
  if (/(siem|splunk|wazuh|elastic|soc\b)/.test(s)) return "SIEM";
  if (/(pentest|penetration|ethical|hacking|ceh|oscp)/.test(s)) return "Pentesting";
  if (/(network|ccna|cisco|firewall|ağ\b)/.test(s)) return "Networking / Security";
  if (/(security|cyber|siber|güvenlik)/.test(s)) return "Cybersecurity";
  if (/(python|java|c\+\+|javascript|programming|yazılım|git|sql|web|software)/.test(s)) return "Software";
  return "Other";
};

const items = rows
  .map((r) => ({
    title: col(r, "name"),
    issuer: col(r, "authority"),
    date: toIso(col(r, "started on")) || toIso(col(r, "finished on")),
    category: guess(col(r, "name")),
    ...(col(r, "license number") ? { credentialId: col(r, "license number") } : {}),
    ...(col(r, "url") ? { url: col(r, "url") } : {}),
  }))
  .filter((x) => x.title)
  .sort((a, b) => b.date.localeCompare(a.date));

const target = resolve(dirname(fileURLToPath(import.meta.url)), "../src/data/credentials.generated.ts");
writeFileSync(
  target,
  `// Generated by scripts/import-linkedin.mjs from a LinkedIn data export. Re-run to refresh.\n// Review the "category" values — they are guessed from the title.\nimport type { Credential } from "../types.ts";\n\nexport const generated: Credential[] = ${JSON.stringify(items, null, 2)};\n`,
);
console.log(`wrote ${items.length} credential(s) to src/data/credentials.generated.ts`);
